export const LANGS = ["az", "ru", "en"] as const;
export type Lang = (typeof LANGS)[number];
export type LocalText = Partial<Record<Lang, string>> & { az: string };

export function isLang(v: string | undefined): v is Lang {
  return !!v && (LANGS as readonly string[]).includes(v);
}

/** Owner-entered text: falls back to AZ when a translation is missing. */
export function tr(text: LocalText | string | undefined, lang: Lang): string {
  if (!text) return "";
  if (typeof text === "string") return text;
  return text[lang] || text.az;
}

